-- NULL VALUE ANALYSIS

-- 1. CUSTOMERS
SELECT COUNT(*) AS NULL_CUSTOMER_ID
FROM customers
WHERE customer_id IS NULL;

SELECT COUNT(*) AS NULL_CUSTOMER_NAME
FROM customers
WHERE CUSTOMER_NAME IS NULL;

SELECT COUNT(*) AS NULL_REGISTRATION_DATE
FROM customers
WHERE REGISTRATION_DATE IS NULL;

-- 2. ORDERS
SELECT COUNT(*) AS NULL_ORDER_ID
FROM ORDERS
WHERE ORDER_ID IS NULL;

SELECT COUNT(*) AS NULL_CUSTOMER_ID
FROM ORDERS
WHERE CUSTOMER_ID IS NULL;

SELECT COUNT(*) AS NULL_ORDER_TOTAL
FROM ORDERS
WHERE ORDER_TOTAL IS NULL;

SELECT COUNT(*) AS NULL_ORDER_DATE
FROM ORDERS
WHERE ORDER_DATE IS NULL;

-- 3. PRODUCTS
SELECT COUNT(*) AS NULL_PRODUCT_ID
FROM products
WHERE product_id IS NULL;

SELECT COUNT(*) AS NULL_CATEGORY
FROM products
WHERE CATEGORY IS NULL;

SELECT COUNT(*) AS NULL_PRICE
FROM products
WHERE PRICE IS NULL;

-- DUPLICATE ANALYSIS

-- 1. ORDERS
SELECT ORDER_ID, COUNT(*) AS OCCURANCE
FROM ORDERS
GROUP BY ORDER_ID
HAVING count(*) > 1;

-- 2. CUSTOMERS
SELECT CUSTOMER_ID, COUNT(*) AS OCCURANCE
FROM customers
group by customer_id
having OCCURANCE > 1;

-- 3. PRODUCTS
select product_id, COUNT(*) AS OCCURANCE
FROM products
group by product_id
having OCCURANCE > 1;

-- REFERENTIAL INTIGRITY CHECKS

-- 1. ORDER WITHOUT CUSTOMERS
SELECT count(*) AS MISSING_CUSTOMER_REFERENCE
FROM orders O
LEFT JOIN customers C
ON O.customer_id = C.customer_id
WHERE C.customer_id IS NULL;

-- 2. ORDER ITEMS WITHOUT ORDERS
SELECT COUNT(*) AS MISSING_ORDER_REFERENCE
FROM order_items OI
LEFT JOIN orders O
ON O.order_id = OI.order_id
WHERE O.order_id IS NULL;

-- 3. ORDER ITEM WITHOUT PRODUCTS
SELECT count(*) AS MISSING_PRODUCT_REFERENCE
FROM order_items OI
LEFT JOIN products P
ON P.product_id = OI.product_id
WHERE P.product_id IS NULL;

-- 4. FEEDBACK WITHOUT ORDERS
SELECT COUNT(*) AS MISSING_ORDER_REFERENCE
FROM customer_feedback CF
LEFT JOIN orders O
ON CF.order_id = O.order_id
WHERE O.order_id IS NULL;

-- INVALID VALUE CHECKS

-- 1. NEGATIVE REVENUE
