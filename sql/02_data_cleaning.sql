-- BUSINESS RULE VALIDATION

-- 1. ORDER TOTAL VALIDATION
SELECT O.ORDER_ID, O.ORDER_TOTAL, SUM(OI.QUANTITY * OI.UNIT_PRICE) AS CALCULATED_TOTAL
FROM orders O
JOIN order_items OI
ON O.order_id = OI.order_id
group by O.order_id, O.order_total
having abs(O.ORDER_TOTAL - CALCULATED_TOTAL) > 1;

-- 2. INVENTORY DAMAGE CHECK
